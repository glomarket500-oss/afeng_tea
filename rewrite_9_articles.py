def replace_article_body(html: str, new_title: str, new_body: str) -> str:
    """替换 <title>、<h1>、article-body 内容，保留 head/schema/nav 结构"""
    # 1. 替换 <title>
    html = re.sub(r"<title>.*?</title>", f"<title>{new_title}</title>", html, count=1)
    # 2. 替换 <h1>（文章主标题）
    html = re.sub(r"<h1>.*?</h1>", f"<h1>{new_title}</h1>", html, count=1)
    # 3. 替换 breadcrumb 最后一项
    html = re.sub(r'(<span>)[^<]*(</span>\s*</div>\s*<article>)', rf'\1{new_title}\2', html)
    # 4. 替换 og:title / twitter:title
    html = re.sub(r'property="og:title" content="[^"]*"', f'property="og:title" content="{new_title}"', html)
    html = re.sub(r'name="twitter:title" content="[^"]*"', f'name="twitter:title" content="{new_title}"', html)
    # 5. 替换 Article schema headline
    html = re.sub(r'"headline"\s*:\s*"[^"]*"', f'"headline": "{new_title}"', html)
    html = re.sub(r'"name"\s*:\s*"[^"]*"', f'"name": "{new_title}"', html)  # BreadcrumbList name
    # 6. 替换 article-body 内容（从 <div class="article-body"> 到下一个 </div> 前）
    # 找到 article-body 开始位置
    m = re.search(r'(<div class="article-body">)(.*?)(</div>\s*<figure)', html, re.DOTALL)
    if m:
        prefix = m.group(1)
        suffix = m.group(3)
        # 保留 lead 段落结构，直接整体替换 body 内容
        new_body_html = prefix + "\n" + new_body + "\n" + suffix
        html = html[:m.start()] + new_body_html + html[m.end():]
    return html

